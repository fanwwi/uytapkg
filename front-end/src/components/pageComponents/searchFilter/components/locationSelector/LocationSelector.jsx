export default function LocationSelector({
  country,
  setCountry,

  region,
  setRegion,

  district,
  setDistrict,
}) {
  const regionOptions = useMemo(() => {
    if (!country) return [];

    return Object.keys(DATA[country] || {});
  }, [country]);

  const districtOptions = useMemo(() => {
    if (!country || !region) return [];

    return DATA[country]?.[region] || [];
  }, [country, region]);

  return (
    <div className={styles.wrapper}>
      <CustomSelect
        icon={MapPin}
        title="Страна"
        value={country}
        setValue={(value) => {
          setCountry(value);
          setRegion("");
          setDistrict("");
        }}
        options={["Кыргызстан", "Турция"]}
      />

      {country && (
        <CustomSelect
          icon={MapPin}
          title={country === "Кыргызстан" ? "Город / Область" : "Город"}
          value={region}
          setValue={(value) => {
            setRegion(value);
            setDistrict("");
          }}
          options={regionOptions}
        />
      )}

      {districtOptions.length > 0 && (
        <CustomSelect
          icon={MapPin}
          title="Район / Населенный пункт"
          value={district}
          setValue={setDistrict}
          options={districtOptions}
        />
      )}
    </div>
  );
}
